int	ft_is_prime(int nb)
{
	int	result;

	result = 2;
	if (nb < 2)
	{
		return (0);
	}
	while (result < nb)
	{
		if (nb % result == 0)
		{
			return (0);
		}
		result++;
	}
	return (1);
}
