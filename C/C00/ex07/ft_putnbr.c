#include <unistd.h>

void	ft_putnbr(int n)
{
	char	tmp;

	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		write(1, "-", 1);
		ft_putnbr(-n);
		return ;
	}
	if (n >= 10)
	{
		ft_putnbr(n / 10);
	}
	tmp = n % 10 + '0';
	write(1, &tmp, 1);
}
