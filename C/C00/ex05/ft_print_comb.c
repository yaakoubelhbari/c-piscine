#include <unistd.h>

void	ft_print_comb(void)
{
	char	p1;
	char	p2;
	char	p3;

	p1 = '0';
	while (p1 <= '7')
	{
		p2 = p1 + 1;
		while (p2 <= '8')
		{
			p3 = p2 + 1;
			while (p3 <= '9')
			{
				write(1, &p1, 1);
				write(1, &p2, 1);
				write(1, &p3, 1);
				if (p1 != '7' || p2 != '8' || p3 != '9')
					write(1, ", ", 2);
				p3++;
			}
			p2++;
		}
		p1++;
	}
}
