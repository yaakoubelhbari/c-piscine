#include <unistd.h>

void	ft_print_comb2(void)
{
	int		p1;
	int		p2;
	char	n;

	p1 = 0;
	while (p1 <= 98)
	{
		p2 = p1 + 1;
		while (p2 <= 99)
		{
			n = (p1 / 10) + '0';
			write(1, &n, 1);
			n = (p1 % 10) + '0';
			write(1, &n, 1);
			write(1, " ", 1);
			n = (p2 / 10) + '0';
			write(1, &n, 1);
			n = (p2 % 10) + '0';
			write(1, &n, 1);
			if (!(p1 == 98 && p2 == 99))
				write(1, ", ", 2);
			p2++;
		}
		p1++;
	}
}
